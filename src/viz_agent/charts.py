"""Chart engine: a typed ChartSpec in, a PNG + the equivalent pandas code + the numbers out.

No code is generated by the LLM or executed with eval/exec. The model only fills
in a spec (kind, columns, aggregation); this module validates it against the data
and draws it. ``code`` is the equivalent hand-written snippet, returned so you can
see and reuse what was done (the lab's "look at the LLM's code" lesson).

Styling follows a validated palette: categorical slots 1-3 (blue, orange, aqua),
a single-hue sequential ramp for heatmaps, thin marks, recessive grid.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

import matplotlib
import matplotlib.colors
import matplotlib.ticker

matplotlib.use("Agg")  # files only - never opens a window
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from .datasets import STORE, DatasetError  # noqa: E402

KINDS = ("count", "bar", "pie", "box", "scatter", "hist", "line", "heatmap")
AGGS = ("mean", "sum", "median", "count", "min", "max")

SURFACE = "#fcfcfb"
INK, INK_2, GRID = "#0b0b0b", "#52514e", "#e6e5e0"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]  # validated for all-pairs use (scatter, pie)
OTHER = "#b9b8b2"
DIVERGING = ["#e34948", "#f0efec", "#2a78d6"]  # red <-> neutral gray <-> blue, for -1..+1 correlations
MAX_SERIES = 3


@dataclass
class ChartSpec:
    kind: str
    x: str = ""
    y: str = ""
    hue: str = ""
    agg: str = "mean"
    title: str = ""


@dataclass
class ChartResult:
    path: str
    kind: str
    title: str
    code: str
    summary: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return {"path": self.path, "kind": self.kind, "title": self.title, "summary": self.summary, "code": self.code}


def chart_dir() -> Path:
    path = Path(os.getenv("CHART_DIR", "charts"))
    path.mkdir(parents=True, exist_ok=True)
    return path


# ------------------------------------------------------------------- validation
def validate(spec: ChartSpec, df: pd.DataFrame) -> ChartSpec:
    kind = spec.kind.strip().lower()
    if kind not in KINDS:
        raise DatasetError(f"Unknown chart kind '{spec.kind}'. Use one of: {', '.join(KINDS)}.")
    agg = (spec.agg or "mean").lower()
    if agg not in AGGS:
        raise DatasetError(f"Unknown aggregation '{spec.agg}'. Use one of: {', '.join(AGGS)}.")
    col = lambda name, numeric=False: STORE.column(df, name, numeric) if name else ""  # noqa: E731
    numeric_y = kind in ("bar", "box", "scatter", "line", "heatmap") or (kind == "pie" and spec.y)
    x = col(spec.x, numeric=kind in ("scatter", "hist"))
    y = col(spec.y, numeric=bool(numeric_y) and agg != "count")
    hue = col(spec.hue)
    needs = {"count": [x], "bar": [x, y], "pie": [x], "box": [x, y], "scatter": [x, y], "hist": [x], "line": [x, y],
             "heatmap": [] if not (x or y or hue) else [x, y, hue]}[kind]
    if not all(needs):
        raise DatasetError(f"A '{kind}' chart needs: " + {"count": "x", "bar": "x and y", "pie": "x (and optional y)",
                           "box": "x and y", "scatter": "x and y", "hist": "x", "line": "x and y",
                           "heatmap": "x, y and hue (or nothing, for a correlation heatmap)"}[kind] + ".")
    return ChartSpec(kind, x, y, hue, agg, spec.title.strip())


# ------------------------------------------------------------------- rendering
def render(spec: ChartSpec, file_name: Optional[str] = None) -> ChartResult:
    df = STORE.load(file_name)
    s = validate(spec, df)
    fig, ax = plt.subplots(figsize=(7.2, 4.2), dpi=144)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    summary = getattr(_Draw, s.kind)(ax, df, s)
    title = s.title or default_title(s)
    ax.set_title(title, color=INK, fontsize=12, loc="left", pad=12, fontweight="bold")
    _style(ax, s.kind)
    fig.tight_layout()
    path = chart_dir() / f"{_slug(s)}.png"
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)
    return ChartResult(str(path), s.kind, title, code_for(s, STORE.resolve(file_name)), summary)


def default_title(s: ChartSpec) -> str:
    agg = {"mean": "Average", "sum": "Total", "median": "Median", "count": "Count of", "min": "Minimum", "max": "Maximum"}[s.agg]
    return {
        "count": f"Number of rows by {s.x}" + (f" and {s.hue}" if s.hue else ""),
        "bar": f"{agg} {s.y} by {s.x}" + (f" and {s.hue}" if s.hue else ""),
        "pie": f"{agg} {s.y} by {s.x}" if s.y else f"Share of rows by {s.x}",
        "box": f"Distribution of {s.y} by {s.x}",
        "scatter": f"{s.y} vs {s.x}",
        "hist": f"Distribution of {s.x}",
        "line": f"{agg} {s.y} by {s.x}" + (f" per {s.hue}" if s.hue else ""),
        "heatmap": f"{agg} {s.y} by {s.hue} and {s.x}" if s.x else "Correlation between numeric columns",
    }[s.kind]


def _slug(s: ChartSpec) -> str:
    parts = [s.kind, s.x, s.y, s.hue, s.agg if s.kind in ("bar", "line", "heatmap", "pie") and s.y else ""]
    return re.sub(r"[^A-Za-z0-9_-]+", "-", "-".join(p for p in parts if p)).strip("-") or s.kind


def _top_levels(series: pd.Series) -> tuple[list, bool]:
    """At most MAX_SERIES levels for colour-coded series; the rest fold into 'Other'."""
    levels = series.value_counts().index.tolist()
    return sorted(levels[:MAX_SERIES], key=str), len(levels) > MAX_SERIES


def _fold(series: pd.Series) -> pd.Series:
    keep, folded = _top_levels(series)
    return series.where(series.isin(keep), "Other") if folded else series


def _rounded(values: pd.Series | dict) -> dict:
    items = values.items() if hasattr(values, "items") else values
    def clean(v):
        if isinstance(v, (int, np.integer)) or (isinstance(v, (float, np.floating)) and float(v).is_integer()):
            return int(v)
        return round(float(v), 3) if isinstance(v, (float, np.floating)) else v
    return {str(k): clean(v) for k, v in list(items)[:24]}


class _Draw:
    @staticmethod
    def count(ax, df, s):
        if s.hue:
            table = pd.crosstab(df[s.x], _fold(df[s.hue]))
            _grouped_bars(ax, table)
            ax.set_ylabel("rows")
            return {"counts": {str(k): _rounded(v) for k, v in table.to_dict(orient="index").items()}}
        counts = df[s.x].value_counts().sort_index()
        _bars(ax, counts)
        ax.set_ylabel("rows")
        return {"counts": _rounded(counts)}

    @staticmethod
    def bar(ax, df, s):
        if s.hue:
            table = df.pivot_table(index=s.x, columns=_fold(df[s.hue]), values=s.y, aggfunc=s.agg)
            _grouped_bars(ax, table)
            ax.set_ylabel(f"{s.agg} {s.y}")
            return {"values": {str(k): _rounded(v) for k, v in table.to_dict(orient="index").items()}}
        values = df.groupby(s.x)[s.y].agg(s.agg)
        _bars(ax, values)
        ax.set_ylabel(f"{s.agg} {s.y}")
        return {"values": _rounded(values), "n": _rounded(df[s.x].value_counts().sort_index())}

    @staticmethod
    def pie(ax, df, s):
        values = df.groupby(s.x)[s.y].agg(s.agg) if s.y else df[s.x].value_counts().sort_index()
        if len(values) > MAX_SERIES + 1:  # fold the tail into "Other"
            top = values.sort_values(ascending=False)
            values = pd.concat([top.iloc[:MAX_SERIES], pd.Series({"Other": top.iloc[MAX_SERIES:].sum()})])
        colors = [SERIES[i] if str(k) != "Other" else OTHER for i, k in enumerate(values.index)]
        wedges, _, _ = ax.pie(values.values, labels=[f"{k}" for k in values.index], colors=colors, startangle=90,
                              counterclock=False, autopct=lambda p: f"{p:.1f}%", pctdistance=0.72,
                              wedgeprops={"linewidth": 2, "edgecolor": SURFACE},
                              textprops={"color": INK, "fontsize": 10})
        for w in wedges:
            w.set_antialiased(True)
        ax.axis("equal")
        return {"values": _rounded(values), "share_pct": _rounded((values / values.sum() * 100).round(1))}

    @staticmethod
    def box(ax, df, s):
        groups = sorted(df[s.x].dropna().unique(), key=lambda v: (str(type(v)), v))
        data = [df.loc[df[s.x] == g, s.y].dropna() for g in groups]
        ax.boxplot(data, tick_labels=[str(g) for g in groups], widths=0.5, patch_artist=True,
                   boxprops={"facecolor": "#d6e6f8", "edgecolor": SERIES[0], "linewidth": 1.2},
                   medianprops={"color": SERIES[0], "linewidth": 2},
                   whiskerprops={"color": INK_2, "linewidth": 1}, capprops={"color": INK_2, "linewidth": 1},
                   flierprops={"marker": "o", "markersize": 4, "markerfacecolor": OTHER, "markeredgecolor": "none"})
        ax.set_xlabel(s.x)
        ax.set_ylabel(s.y)
        medians = {str(g): float(d.median()) for g, d in zip(groups, data)}
        return {"median": _rounded(medians), "n": {str(g): int(len(d)) for g, d in zip(groups, data)}}

    @staticmethod
    def scatter(ax, df, s):
        x, y = df[s.x], df[s.y]
        discrete = x.nunique() <= 12
        jitter = np.random.default_rng(0).uniform(-0.18, 0.18, len(df)) if discrete else 0
        if s.hue:
            hue = _fold(df[s.hue])
            for i, level in enumerate(sorted(hue.unique(), key=str)):
                m = hue == level
                ax.scatter(x[m] + (jitter[m] if discrete else 0), y[m], s=26, alpha=0.65,
                           color=SERIES[i] if level != "Other" else OTHER, edgecolor=SURFACE, linewidth=0.6, label=str(level))
            if not discrete:
                ax.legend(frameon=False, fontsize=9, title=s.hue, title_fontsize=9)
        else:
            ax.scatter(x + jitter, y, s=26, alpha=0.55, color=SERIES[0], edgecolor=SURFACE, linewidth=0.6,
                       label="rows (jittered)" if discrete else "rows")
        if discrete:  # mean per level makes the trend readable through the overplotting
            means = df.groupby(s.x)[s.y].mean()
            ax.plot(means.index, means.values, color=INK, linewidth=2, marker="o", markersize=8,
                    markeredgecolor=SURFACE, markeredgewidth=2, label="mean", zorder=3)
            ax.legend(frameon=False, fontsize=9, loc="best", title=s.hue or None, title_fontsize=9)
        ax.set_xlabel(s.x)
        ax.set_ylabel(s.y)
        r = float(x.corr(y))
        out = {"pearson_r": round(r, 3), "n": int(len(df))}
        if discrete:
            out["mean_by_x"] = _rounded(df.groupby(s.x)[s.y].mean())
        return out

    @staticmethod
    def hist(ax, df, s):
        counts, edges, _ = ax.hist(df[s.x].dropna(), bins="auto", color=SERIES[0], edgecolor=SURFACE, linewidth=2)
        ax.set_xlabel(s.x)
        ax.set_ylabel("rows")
        col = df[s.x]
        return {"mean": round(float(col.mean()), 3), "median": round(float(col.median()), 3),
                "min": float(col.min()), "max": float(col.max()), "bins": int(len(counts))}

    @staticmethod
    def line(ax, df, s):
        if s.hue:
            table = df.pivot_table(index=s.x, columns=_fold(df[s.hue]), values=s.y, aggfunc=s.agg).sort_index()
            for i, col in enumerate(table.columns):
                ax.plot(table.index.astype(str), table[col], color=SERIES[i] if col != "Other" else OTHER, linewidth=2,
                        label=str(col))
            ax.legend(frameon=False, fontsize=9, loc="upper left", title=s.hue, title_fontsize=9)
            summary = {"values": {str(k): _rounded(v) for k, v in table.to_dict(orient="index").items()}}
        else:
            values = df.groupby(s.x)[s.y].agg(s.agg).sort_index()
            ax.plot(values.index.astype(str), values.values, color=SERIES[0], linewidth=2)
            summary = {"values": _rounded(values)}
        ax.set_xlabel(s.x)
        ax.set_ylabel(f"{s.agg} {s.y}")
        ax.tick_params(axis="x", rotation=45)
        ax.margins(x=0.08)
        return summary

    @staticmethod
    def heatmap(ax, df, s):
        if s.x:
            table = df.pivot_table(index=s.hue, columns=s.x, values=s.y, aggfunc=s.agg)
            im = ax.imshow(table.values, cmap="Blues", aspect="auto")  # magnitude -> one hue, light to dark
            dark = lambda v: v > np.nanmin(table.values) + 0.6 * np.ptp(table.values)  # noqa: E731
        else:
            table = df.select_dtypes("number").corr().round(2)
            cmap = matplotlib.colors.LinearSegmentedColormap.from_list("diverging", DIVERGING)
            im = ax.imshow(table.values, cmap=cmap, vmin=-1, vmax=1, aspect="auto")  # polarity -> two hues, gray at 0
            dark = lambda v: abs(v) > 0.6  # noqa: E731
        ax.set_xticks(range(len(table.columns)), [str(c) for c in table.columns], rotation=45, ha="right")
        ax.set_yticks(range(len(table.index)), [str(i) for i in table.index])
        for (i, j), v in np.ndenumerate(table.values):
            ax.text(j, i, compact(v), ha="center", va="center", fontsize=7.5, color="white" if dark(v) else INK)
        bar = ax.figure.colorbar(im, ax=ax, fraction=0.035, pad=0.02)
        bar.outline.set_visible(False)
        bar.ax.tick_params(colors=INK_2, labelsize=8)
        ax.grid(False)
        return {"values": {str(k): _rounded(v) for k, v in table.to_dict(orient="index").items()}}


def _bars(ax, values: pd.Series) -> None:
    labels = [str(i) for i in values.index]
    ax.bar(labels, values.values, color=SERIES[0], width=0.6, edgecolor=SURFACE, linewidth=2)
    for i, v in enumerate(values.values):
        ax.annotate(f"{v:,.2f}" if isinstance(v, float) and not float(v).is_integer() else f"{v:,.0f}",
                    (i, v), xytext=(0, 3), textcoords="offset points", ha="center", color=INK_2, fontsize=9)
    ax.set_xlabel(values.index.name or "")


def _grouped_bars(ax, table: pd.DataFrame) -> None:
    n = len(table.columns)
    width = 0.8 / n
    x = np.arange(len(table.index))
    for i, col in enumerate(table.columns):
        ax.bar(x + (i - (n - 1) / 2) * width, table[col].values, width=width * 0.92,
               color=SERIES[i] if col != "Other" else OTHER, edgecolor=SURFACE, linewidth=2, label=str(col))
    ax.set_xticks(x, [str(i) for i in table.index])
    ax.set_xlabel(table.index.name or "")
    ax.legend(frameon=False, fontsize=9, title=table.columns.name, title_fontsize=9)


def compact(v: float) -> str:
    """12345 -> '12.3k', 2_100_000 -> '2.1M' (keeps dense labels inside their cells)."""
    a = abs(v)
    if a >= 1e6:
        return f"{v / 1e6:.1f}M"
    if a >= 1e3:
        return f"{v / 1e3:.0f}k" if a >= 1e5 else f"{v / 1e3:.1f}k"
    return f"{v:.2f}" if not float(v).is_integer() else f"{v:.0f}"


def _style(ax, kind: str) -> None:
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=9)
    ax.xaxis.label.set_color(INK_2)
    ax.yaxis.label.set_color(INK_2)
    if kind not in ("pie", "heatmap"):
        ax.grid(axis="y", color=GRID, linewidth=0.8)
        ax.set_axisbelow(True)
        ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: compact(v) if abs(v) >= 1e3 else f"{v:g}"))


# ------------------------------------------------------------------- equivalent code
def code_for(s: ChartSpec, file_name: str) -> str:
    """The plain pandas/matplotlib code a person (or the lab's LLM) would write for this chart."""
    head = f"import pandas as pd\nimport matplotlib.pyplot as plt\n\ndf = pd.read_csv('data/{file_name}')\n"
    body = {
        "count": f"df.groupby(['{s.x}', '{s.hue}']).size().unstack().plot(kind='bar')" if s.hue
        else f"df['{s.x}'].value_counts().sort_index().plot(kind='bar')",
        "bar": f"df.pivot_table(index='{s.x}', columns='{s.hue}', values='{s.y}', aggfunc='{s.agg}').plot(kind='bar')" if s.hue
        else f"df.groupby('{s.x}')['{s.y}'].{s.agg}().plot(kind='bar')",
        "pie": (f"df.groupby('{s.x}')['{s.y}'].{s.agg}()" if s.y else f"df['{s.x}'].value_counts()") + ".plot(kind='pie', autopct='%1.1f%%')",
        "box": f"df.boxplot(column='{s.y}', by='{s.x}')",
        "scatter": f"df.plot(kind='scatter', x='{s.x}', y='{s.y}')\nprint(df['{s.x}'].corr(df['{s.y}']))",
        "hist": f"df['{s.x}'].plot(kind='hist', bins=20)",
        "line": f"df.pivot_table(index='{s.x}', columns='{s.hue}', values='{s.y}', aggfunc='{s.agg}').plot()" if s.hue
        else f"df.groupby('{s.x}')['{s.y}'].{s.agg}().plot()",
        "heatmap": (f"table = df.pivot_table(index='{s.hue}', columns='{s.x}', values='{s.y}', aggfunc='{s.agg}')"
                    "\nplt.imshow(table, cmap='Blues'); plt.colorbar()" if s.x
                    else "table = df.select_dtypes('number').corr()"
                    "\nplt.imshow(table, cmap='RdBu', vmin=-1, vmax=1); plt.colorbar()"),
    }[s.kind]
    lines = body.split("\n")
    prints = [line for line in lines if line.startswith("print(")]
    plot = [line for line in lines if not line.startswith("print(")]
    tail = [f"plt.title({(s.title or default_title(s))!r})", f"plt.savefig('{_slug(s)}.png')", *prints]
    return head + "\n".join(plot + tail)
